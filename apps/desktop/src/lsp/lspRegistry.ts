export function detectInstalledLanguageServers(): LanguageServerInfo[] {
  const isWindows = process.platform === 'win32';
  const checkCmd = isWindows ? 'where' : 'which';

  return languageRegistry.map((item) => {
    if (item.bundled) {
      return { ...item, available: true, detectedPath: 'monaco-internal' };
    }

    try {
      const output = execSync(`${checkCmd} ${item.binaryName}`, {
        stdio: ['pipe', 'pipe', 'ignore'],
        timeout: 1000,
        encoding: 'utf8',
      }).trim();

      const firstPath = output.split('\n')[0].trim();
      return {
        ...item,
        available: Boolean(firstPath),
        detectedPath: firstPath || undefined,
      };
    } catch {
      return {
        ...item,
        available: false,
      };
    }
  });
}
